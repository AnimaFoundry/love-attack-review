from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OPTIONS = {"temperature": 0, "seed": 20261026, "num_ctx": 4096, "num_predict": 256}
ARM_ORDER = ["schema_evidence", "raw_no_evidence", "schema_no_evidence", "raw_evidence"]


def build_tasks():
    # The expected state/value/row tuples below were specified manually.
    # They are not generated by the source parser or a model.
    definitions = [
        ("T01", "tray-register-f4", 2, "ready_slots",
         [("reserve_slots", 8), ("ready_slots", 0), ("sealed_slots", 0)],
         "observed_zero", "observed", 0, 1),
        ("T02", "panel-readout-k7", 5, "active_lamps",
         [("active_lamps", 0), ("spare_lamps", 16), ("inspection_marks", 4)],
         "observed_zero", "observed", 0, 0),
        ("T03", "shelf-audit-m2", 4, "blue_bins",
         [("orange_bins", 3), ("blue_bins", 11), ("empty_bins", 11)],
         "observed_positive", "observed", 11, 1),
        ("T04", "parcel-count-v9", 1, "labelled_packs",
         [("reserved_packs", 6), ("torn_labels", 0), ("labelled_packs", 27), ("spare_labels", 9)],
         "observed_positive", "observed", 27, 2),
        ("T05", "batch-note-r6", 7, "dry_weight",
         [("dry_weight", None), ("sample_count", 14), ("tray_count", 0)],
         "explicit_unknown", "unknown", None, 0),
        ("T06", "meter-register-s3", 2, "reference_level",
         [("channel_count", 5), ("backup_level", None), ("offset_steps", 0), ("reference_level", None)],
         "explicit_unknown", "unknown", None, 3),
        ("T07", "parts-ledger-b8", 3, "polished_units",
         [("raw_units", 19), ("rejected_units", 0), ("painted_units", None)],
         "absent_target", "absent", None, None),
        ("T08", "station-note-j5", 6, "aligned_guides",
         [("stored_guides", 7), ("marked_guides", None), ("bent_guides", 0), ("spare_guides", 2)],
         "absent_target", "absent", None, None),
    ]
    tasks = []
    for task_id, document_id, revision, target, pairs, group, state, value, row in definitions:
        source = {"document_id": document_id, "revision": revision, "complete": True,
                  "entries": [{"key": k, "value": v} for k, v in pairs]}
        source_text = json.dumps(source, ensure_ascii=False, separators=(",", ":"))
        digest = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
        tasks.append({
            "input_id": task_id, "group": group, "source_text": source_text,
            "source_sha256": digest, "target_key": target,
            "trusted_metadata": {"document_id": document_id, "revision": revision, "sha256": digest},
            "expected": {"state": state, "value": value, "row": row},
        })
    return {"study": "BF-01C", "status": "DEVELOPMENT_NOT_CONFIRMATORY",
            "provenance": "New original synthetic records, authored 2026-10-26; no private or prior pilot records.",
            "source_encoding": "Exact source_text UTF-8; no terminal newline is added to source bytes.",
            "expected_answers": "Manually specified semantic state/value/row; SHA-256 computed from exact authored bytes.",
            "tasks": tasks}


def system_prompt(contract, schema):
    return (
        "Complete a closed-record extraction task. The supplied record has complete=true, "
        "so entries are the entire record for this task. The externally specified target_key "
        "must be matched exactly against entry keys. If the target exists with an integer value, "
        "state is observed and value is that integer, including zero. If it exists with null, "
        "state is unknown and value is null. If the target key is absent, state is absent and "
        "value is null. Do not replace null or absence with zero. Do not invent a default. "
        "Return exactly one JSON object, without Markdown fences or surrounding prose. "
        + ("The response must contain exactly state and value. Do not include evidence. "
           if contract == "no_evidence" else
           "Include evidence with document_id, revision and sha256 copied from trusted_metadata, "
           "key equal to target_key, and row equal to the zero-based entry index when present; "
           "row is null when absent. Copy the supplied hash; do not calculate it. ")
        + "Follow this response schema: " + json.dumps(schema, ensure_ascii=False, separators=(",", ":"))
    )


def build_requests(task_document, model):
    schemas = {c: json.loads((HERE / f"schema_{c}.json").read_text(encoding="utf-8"))
               for c in ("no_evidence", "evidence")}
    requests = []
    for index, task in enumerate(task_document["tasks"]):
        shift = index % 4
        arms = ARM_ORDER[shift:] + ARM_ORDER[:shift]
        for arm in arms:
            mode, contract = arm.split("_", 1)
            schema = schemas[contract]
            user_payload = {"source_text": task["source_text"], "target_key": task["target_key"],
                            "trusted_metadata": task["trusted_metadata"]}
            body = {"model": model,
                    "messages": [{"role": "system", "content": system_prompt(contract, schema)},
                                 {"role": "user", "content": json.dumps(user_payload, ensure_ascii=False, separators=(",", ":"))}],
                    "stream": False, "options": dict(OPTIONS)}
            if mode == "schema":
                body["format"] = schema
            requests.append({"request_id": f"BF01C-{task['input_id']}-{arm}",
                             "input_id": task["input_id"], "arm": arm,
                             "mode": mode, "contract": contract, "request_body": body})
    return requests


def encode(document):
    return (json.dumps(document, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True, help="Exact installed model name; never downloaded here")
    args = parser.parse_args()
    tasks = build_tasks()
    outputs = {HERE / "tasks.json": encode(tasks), HERE / "requests.json": encode(build_requests(tasks, args.model))}
    for path, data in outputs.items():
        if path.exists() and path.read_bytes() != data:
            raise SystemExit(f"Refusing to replace differing prepared file: {path.name}")
    for path, data in outputs.items():
        if not path.exists():
            with path.open("xb") as handle:
                handle.write(data)
    print(json.dumps({"inputs": 8, "requests": 32, "first_arm": "schema_evidence", "model_calls": 0}))


if __name__ == "__main__":
    main()
